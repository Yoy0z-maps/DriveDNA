import java.util.Properties

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.android)
    alias(libs.plugins.kotlin.compose)
}

// Release signing values live outside the repository. Override the location with
// -Pdrivedna.signing=/path/to/signing.properties; without the file, release builds are unsigned.
val signingFile = file(
    providers.gradleProperty("drivedna.signing").orNull
        ?: "${System.getProperty("user.home")}/.android-keys/drivedna/signing.properties"
)
val signingProps = Properties().apply {
    if (signingFile.isFile) signingFile.inputStream().use { load(it) }
}

android {
    namespace = "dev.drivedna.app"
    compileSdk = 35
    useLibrary("android.car")

    defaultConfig {
        applicationId = "dev.drivedna.app"
        minSdk = 28
        targetSdk = 35
        versionCode = 5
        versionName = "0.5.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (signingProps.isNotEmpty()) {
            create("release") {
                storeFile = file(signingProps.getProperty("storeFile"))
                storePassword = signingProps.getProperty("storePassword")
                keyAlias = signingProps.getProperty("keyAlias")
                keyPassword = signingProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // R8 off: no verified keep rules for the Pleos SDK / Car API yet, and stability
            // matters more than APK size for the contest build.
            isMinifyEnabled = false
            signingConfig = signingConfigs.findByName("release")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures {
        compose = true
        buildConfig = true
    }
}

